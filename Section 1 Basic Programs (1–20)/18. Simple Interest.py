principal = float(input("ENTER PRINCIPAL AMOUNT: "))
rate = float(input("ENTER RATE OF INTEREST: "))
time = float(input("ENTER TIME (YEAR): "))

simple_interest = (principal * rate * time) / 100

print("SIMPLE INTEREST -", simple_interest)

